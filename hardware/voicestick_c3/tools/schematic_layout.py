"""Hand layout of schematic blocks, read by build_schematic.py.

Block-local coordinates in mm, y down, on the 1.27 mm grid. Per block:
  parts   ref -> (x, y) or (x, y, rotation in degrees, counter-clockwise)
  wires   polylines of 'REF.PIN' tokens and (x, y) points; a corner is
          inserted (horizontal first) between points that are not aligned,
          and a lone 'REF.PIN' marks a pin that sits on another wire
  labels  (net, (x, y), direction) global labels for nets leaving the block
  names   (net, (x, y)) local labels on a wire, naming nets kept inside the block
  power   (net, (x, y)[, direction]) GND / +3V3 symbols at wire ends
Pins a block does not wire get a stub with a label or power symbol, so a
layout only changes the drawing; design.py remains the netlist.
"""



def key(sw, pull_up, x, y, net, note):
    """Key to GND with a pull-up from +3V3 on its MCU line, entering from the left."""
    return {
        'parts': {sw: (x + 30.48, y), pull_up: (x + 17.78, y - 5.08)},
        'wires': [[f'{sw}.1', (x + 7.62, y)], [f'{pull_up}.2', (x + 17.78, y)],
                  [f'{sw}.2', (x + 40.64, y), (x + 40.64, y + 2.54)]],
        'labels': [(net, (x + 7.62, y), 'left')],
        'power': [('GND', (x + 40.64, y + 2.54))],
        'texts': [(note, (x + 2.54, y + 7.62))],
    }


def merge(*specs):
    out = {}
    for spec in specs:
        for k, v in spec.items():
            if isinstance(v, dict):
                out.setdefault(k, {}).update(v)
            else:
                out.setdefault(k, []).extend(v)
    return out


